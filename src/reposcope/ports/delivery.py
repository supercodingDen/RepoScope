"""SDK-independent durable delivery boundaries."""

from __future__ import annotations

from typing import Protocol
from uuid import UUID

from reposcope.domain.delivery import (
    Complete,
    DeliveryEvent,
    DeliveryPolicy,
    Lease,
    OutboxClaim,
    PermanentFailure,
    PublicationEvent,
)


class DeliveryMessage(Protocol):
    @property
    def data(self) -> bytes: ...

    @property
    def subject(self) -> str: ...

    async def ack_sync(self, timeout: float = 1.0) -> object: ...
    async def nak(self, delay: int | float | None = None) -> None: ...
    async def term(self) -> None: ...
    async def in_progress(self) -> None: ...


class DeliveryBroker(Protocol):
    async def publish(self, event: PublicationEvent) -> None: ...
    async def fetch_one(self, consumer: str) -> DeliveryMessage | None: ...
    async def flush(self) -> None: ...
    def subject(self, event_type: str) -> str: ...


class DeliveryRepository(Protocol):
    @property
    def policy(self) -> DeliveryPolicy: ...

    async def claim_outbox(self, owner: UUID) -> OutboxClaim | None: ...
    async def mark_published(self, claim: OutboxClaim) -> None: ...
    async def retry_publication(self, claim: OutboxClaim, delay: float) -> None: ...
    async def authorized(self, event: DeliveryEvent) -> bool: ...
    async def quarantine(self, data: bytes, consumer: str, reason: str) -> None: ...
    async def completed(self, consumer: str, event_id: UUID) -> bool: ...
    async def claim(self, event: DeliveryEvent, consumer: str, owner: UUID) -> Lease | None: ...
    async def renew(self, lease: Lease) -> None: ...
    async def release(
        self, lease: Lease, delay: float, *, refund_attempt: bool = False
    ) -> None: ...
    async def finalize(self, lease: Lease, outcome: Complete | PermanentFailure) -> None: ...
    async def reconcile(self) -> int: ...
